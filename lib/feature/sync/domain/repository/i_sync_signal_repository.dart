/// Сигнал «локальные данные изменились».
///
/// Развязывает блоки фич и `SyncBloc`: фича только сообщает о правке и
/// ничего не знает про синхронизацию, а `SyncBloc` слушает поток и сам
/// решает, запускать прогон или нет (у гостя, например, не запускать).
///
/// Именно репозиторий, а не обёртка над блоком: блок не должен обращаться
/// к другому блоку, оба работают с общей зависимостью данных.
abstract interface class ISyncSignalRepository {
  /// Поток сигналов о локальных правках.
  ///
  /// Без данных: важен сам факт правки, а что именно изменилось,
  /// синхронизация выяснит из `sync_state` строк.
  Stream<void> get localMutations;

  /// Сообщить, что локальные данные изменились.
  void notifyLocalMutation();
}
