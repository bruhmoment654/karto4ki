/// Что синхронизации нужно знать про авторизацию.
///
/// Отдельный тип, а не ссылка на `AuthBloc`: `SyncBloc` тестируется без
/// блока авторизации, а DI остаётся линейным.
enum SyncAuthStatus {
  /// Гость: синхронизации нет вовсе, индикатор не показываем.
  none,

  /// Сессия действует.
  active,

  /// Токен протух. Прогоны не запускаем — иначе будем молотить 401 в цикле.
  expired,
}
