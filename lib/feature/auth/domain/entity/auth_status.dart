/// Статус сессии — факт из слоя данных, а не состояние экрана.
///
/// `authorizing` здесь нет намеренно: «идёт вход» — это состояние UI,
/// оно живёт в `AuthState` и в хранилище токенов не отражается.
enum AuthStatus {
  /// Хранилище ещё не прочитано.
  unknown,

  /// Токенов нет.
  unauthorized,

  /// Токены есть и действуют.
  authorized,

  /// Refresh не удался — нужен перелогин. Токены уже вычищены.
  expired,
}
